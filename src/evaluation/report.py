"""Aggregate benchmark runs into comparison tables.

    python -m evaluation.report                       # -> results/summary/baseline_summary.{md,csv}
    python -m evaluation.report --results results --manifest data/benchmark_manifest.csv

For every (model, run tag) the latest run is taken. Metrics are *recomputed* from
predictions.jsonl against the current ground truth for each page group (core / mixed /
all), and a model appears in a group's table only if it has predictions for every page
of that group — so all numbers in one table refer to exactly the same pages.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import yaml

from benchmark.manifest import read_manifest, resolve
from evaluation.evaluate import load_predictions
from evaluation.scoring import score_run
from ocr.registry import SPECS

GROUPS = {"core": lambda r: r.get("subset") == "core",
          "mixed": lambda r: r.get("subset") == "mixed",
          "all": lambda r: True}


def latest_runs(results: Path) -> list[Path]:
    best: dict[tuple[str, str], Path] = {}
    for metrics_path in sorted(results.glob("*/*/metrics.json")):
        run_dir = metrics_path.parent
        m = json.loads(metrics_path.read_text())
        if m.get("status") not in ("ok", "partial"):
            continue
        tag = run_dir.name.split("-", 2)[2] if run_dir.name.count("-") >= 2 else ""
        best[(run_dir.parent.name, tag)] = run_dir  # sorted -> last timestamp wins
    return list(best.values())


def pct(x: float | None) -> str:
    return "—" if x is None else f"{100 * x:.1f}"


def num(x: float | None, digits: int = 1) -> str:
    return "—" if x is None else f"{x:.{digits}f}"


def build(results: Path, manifest: Path) -> tuple[str, list[dict]]:
    rows = [r for r in read_manifest(manifest) if r["ground_truth_path"] and r["split"] == "test"]
    gts = {r["id"]: resolve(manifest, r["ground_truth_path"]).read_text(encoding="utf-8") for r in rows}
    runs = []
    for run_dir in latest_runs(results):
        cfg = yaml.safe_load((run_dir / "config.yaml").read_text())
        metrics = json.loads((run_dir / "metrics.json").read_text())
        preds = load_predictions(run_dir / "predictions.jsonl")
        runs.append({"dir": run_dir, "model": run_dir.parent.name, "cfg": cfg, "metrics": metrics, "preds": preds,
                     "preprocess": cfg["args"].get("preprocess") or "original"})

    md: list[str] = ["# Baseline summary (auto-generated by `python -m evaluation.report`)", ""]
    csv_rows: list[dict] = []
    for group, keep in GROUPS.items():
        g_rows = [r for r in rows if keep(r)]
        if not g_rows:
            continue
        ids = {r["id"] for r in g_rows}
        table = []
        for run in runs:
            ok_ids = {i for i, p in run["preds"].items() if not p.get("error")}
            if not ids <= set(run["preds"]):
                continue
            s = score_run(g_rows, gts, run["preds"])
            o = s["overall"]
            spec = SPECS.get(run["model"])
            entry = {
                "group": group, "model": run["model"], "preprocess": run["preprocess"],
                "pages": o["pages"], "failed": len(ids - ok_ids), "documents": o["documents"],
                "cer": o["cer"], "wer": o["wer"], "cer_normalized": o["cer_normalized"],
                "wer_normalized": o["wer_normalized"], "cer_loose": o["cer_loose"],
                "cer_arabic_only": o["cer_arabic_only"], "bow_f1": o["bow_f1"],
                "sec_per_page": s["runtime"]["per_page_mean_s"],
                "load_s": run["metrics"].get("runtime", {}).get("load_s"),
                "peak_rss_mb": run["metrics"].get("memory", {}).get("peak_rss_mb"),
                "license": spec.license if spec else "", "commercial": spec.commercial_use if spec else "",
                "model_version": run["metrics"].get("model_version"), "run_dir": str(run["dir"]),
                "by_source": {k: v["cer_normalized"] for k, v in s["by_source_id"].items()},
                "confusions": s["confusions_top"][:15],
            }
            table.append(entry)
        if not table:
            continue
        table.sort(key=lambda e: e["cer_normalized"])
        csv_rows += table
        md += [f"## Pages: `{group}` ({len(g_rows)} pages, {len({r['source_id'] for r in g_rows})} sources)", "",
               "| model | preprocess | CER % | WER % | norm. CER % | norm. WER % | loose CER % | arabic-only CER % "
               "| BoW-F1 % | s/page | load s | peak RSS MB | licence (commercial) |",
               "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for e in table:
            fail = f" ({e['failed']} failed)" if e["failed"] else ""
            md.append(f"| {e['model']}{fail} | {e['preprocess']} | {pct(e['cer'])} | {pct(e['wer'])} | "
                      f"**{pct(e['cer_normalized'])}** | {pct(e['wer_normalized'])} | {pct(e['cer_loose'])} | "
                      f"{pct(e['cer_arabic_only'])} | {pct(e['bow_f1'])} | "
                      f"{num(e['sec_per_page'])} | {num(e['load_s'], 0)} | {e['peak_rss_mb'] or '—'} | "
                      f"{e['license']} ({e['commercial']}) |")
        sources = sorted({s for e in table for s in e["by_source"]})
        md += ["", "Normalized CER % by source:", "",
               "| model | preprocess | " + " | ".join(sources) + " |", "|---|---|" + "---|" * len(sources)]
        for e in table:
            md.append(f"| {e['model']} | {e['preprocess']} | " +
                      " | ".join(pct(e["by_source"].get(s)) for s in sources) + " |")
        md.append("")

    # Preprocessing effect: same model, same pages, original vs other configs.
    pre_lines = []
    for group in GROUPS:
        by_model: dict[str, dict[str, dict]] = {}
        for e in csv_rows:
            if e["group"] == group:
                by_model.setdefault(e["model"], {})[e["preprocess"]] = e
        for model, variants in sorted(by_model.items()):
            base = variants.get("original")
            for name, e in variants.items():
                if base and name != "original":
                    pre_lines.append(f"| {group} | {model} | {name} | {pct(base['cer'])} → {pct(e['cer'])} | "
                                     f"{pct(base['cer_normalized'])} → {pct(e['cer_normalized'])} | "
                                     f"{100 * (e['cer_normalized'] - base['cer_normalized']):+.1f} |")
    if pre_lines:
        md += ["## Preprocessing: OCR(original) vs OCR(preprocessed) on the same pages", "",
               "| pages | model | config | CER % | norm. CER % | Δ norm. CER (pp) |", "|---|---|---|---|---|---|",
               *pre_lines, ""]

    core_entries = [e for e in csv_rows if e["group"] == "core"]
    if core_entries:
        best = min(core_entries, key=lambda e: e["cer_normalized"])
        md += [f"## Top character confusions (standard profile, core pages) — {best['model']} ({best['preprocess']})", "",
               "| reference | hypothesis | count |", "|---|---|---|"]
        for r, h, n in best["confusions"]:
            md.append(f"| {r!r} U+{ord(r):04X} | {h!r}{f' U+{ord(h):04X}' if h else ''} | {n} |"
                      if r else f"| (insert) | {h!r} U+{ord(h):04X} | {n} |")
        md.append("")
    return "\n".join(md), csv_rows


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", default="results")
    p.add_argument("--manifest", default="data/benchmark_manifest.csv")
    p.add_argument("--out", default="results/summary")
    args = p.parse_args(argv)

    md, rows = build(Path(args.results), Path(args.manifest))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "baseline_summary.md").write_text(md + "\n", encoding="utf-8")
    fields = ["group", "model", "preprocess", "pages", "failed", "documents", "cer", "wer", "cer_normalized",
              "wer_normalized", "cer_loose", "cer_arabic_only", "bow_f1", "sec_per_page", "load_s",
              "peak_rss_mb", "license", "commercial", "model_version", "run_dir"]
    with (out / "baseline_summary.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
